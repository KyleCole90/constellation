export const CLAUDE_CODE_MINIMUM = "2.1.323";

export const olderThan = (have: string, need: string): boolean => {
  const a = have.split(".").map(Number);
  const b = need.split(".").map(Number);
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    const x = a[i] ?? 0;
    const y = b[i] ?? 0;
    if (x !== y) return x < y;
  }
  return false;
};
